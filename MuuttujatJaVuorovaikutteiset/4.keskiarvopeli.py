print("Kirjoita kolme lukua, niin lasketaan niiden keskiarvo")

luku1 = float(input("Kirjoita ensimmäinen luku: "))
luku2 = float(input("Kirjoita toinen luku: "))
luku3 = float(input("Kirjoita kolmas luku: "))

keskiarvo = (luku1 + luku2 + luku3) / 3

print("Lukujen keskiarvo on: " + str(keskiarvo))